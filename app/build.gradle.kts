// Release signing is supplied only by CI (see .github/workflows/android-release.yml).
// Nothing secret is ever stored in the repository.
val releaseKeystore = System.getenv("MONO_KEYSTORE_PATH")
    ?.let { file(it) }
    ?.takeIf { it.exists() }

android {
    namespace = "com.shoron.mono"
    compileSdk = 35

    defaultConfig {
        applicationId = "com.shoron.mono"
        minSdk = 26
        targetSdk = 35
        versionCode = (findProperty("monoVersionCode") as String?)?.toInt() ?: 1
        versionName = (findProperty("monoVersionName") as String?) ?: "0.1.0"
    }

    signingConfigs {
        if (releaseKeystore != null) {
            create("release") {
                storeFile = releaseKeystore
                storePassword = System.getenv("MONO_KEYSTORE_PASSWORD")
                keyAlias = System.getenv("MONO_KEY_ALIAS")
                keyPassword = System.getenv("MONO_KEY_PASSWORD")
            }
        }
    }

    buildTypes {
        debug {
            applicationIdSuffix = ".debug"
            versionNameSuffix = "-debug"
            resValue("string", "app_name", "MONO dev")
        }
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro",
            )
            signingConfig = signingConfigs.findByName("release")
            resValue("string", "app_name", "MONO")
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    buildFeatures {
        compose = true
        buildConfig = true
    }

    lint {
        abortOnError = false
        checkReleaseBuilds = false
    }

    packaging {
        resources.excludes += "/META-INF/{AL2.0,LGPL2.1}"
    }
}

